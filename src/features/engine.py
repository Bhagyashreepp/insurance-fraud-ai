"""Create claim-level features using only information available at decision time.

``fraud_label``, injected scenario metadata, and post-outcome fields are never
read by this module. Historical aggregates use claims with a strictly earlier
``submitted_date``; claims submitted on the same date are processed together.
"""

from __future__ import annotations

import argparse
import logging
import re
from collections import defaultdict, deque
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sqlalchemy import select

from src.db.database import DEFAULT_DATABASE_PATH, create_engine, get_session_factory
from src.db.models import Claim, Document, Policy

from .config import FeatureConfig
from src.models.narrative_similarity import NarrativeSimilarityAnalyzer

LOGGER = logging.getLogger(__name__)
WORD_PATTERN = re.compile(r"\b\w+\b")
SENTENCE_PATTERN = re.compile(r"[.!?]+")


def _policy_active(policy: pd.Series | None, incident_date: pd.Timestamp) -> int:
    """Return whether policy information supports active status at the incident."""
    if policy is None:
        return 0
    return int(
        policy["policy_status"] == "active"
        and pd.Timestamp(policy["effective_date"]) <= incident_date <= pd.Timestamp(policy["expiration_date"])
    )


def _mean_and_std(stats: list[float]) -> tuple[float, float]:
    """Return population mean/std for an historical amount list, or zeroes."""
    if not stats:
        return 0.0, 0.0
    values = np.asarray(stats, dtype=float)
    return float(values.mean()), float(values.std(ddof=0))


def _document_features(documents: pd.DataFrame, submitted_date: pd.Timestamp, incident_date: pd.Timestamp) -> tuple[int, float, int]:
    """Calculate current-claim document features limited to documents available at T."""
    available = documents.loc[pd.to_datetime(documents["uploaded_date"]) <= submitted_date]
    if available.empty:
        return 0, np.nan, 1
    differences = (pd.to_datetime(available["document_date"]) - incident_date).abs().dt.days
    return len(available), float(differences.min()), 0


def _base_feature_row(claim: pd.Series, policy: pd.Series | None, claim_documents: pd.DataFrame) -> dict[str, Any]:
    """Build current-claim-only values that do not require historical state."""
    submitted_date = pd.Timestamp(claim["submitted_date"])
    incident_date = pd.Timestamp(claim["incident_date"])
    narrative = str(claim["narrative"])
    document_count, document_date_difference, missing_document = _document_features(claim_documents, submitted_date, incident_date)
    return {
        "claim_id": claim["claim_id"],
        "submitted_date": submitted_date,
        "claim_amount": float(claim["claim_amount"]),
        "incident_to_submission_delay_days": int((submitted_date - incident_date).days),
        "policy_active_indicator": _policy_active(policy, incident_date),
        "document_count": document_count,
        "document_incident_date_difference_days": document_date_difference,
        "missing_document_indicator": missing_document,
        "description_length": len(narrative),
        "word_count": len(WORD_PATTERN.findall(narrative)),
        "sentence_count": len(SENTENCE_PATTERN.findall(narrative)),
    }


def build_claim_features(
    claims: pd.DataFrame,
    policies: pd.DataFrame,
    documents: pd.DataFrame,
    config: FeatureConfig | None = None,
    similarity_analyzer: NarrativeSimilarityAnalyzer | None = None,
    include_similarity: bool = True,
) -> pd.DataFrame:
    """Return point-in-time features for claims.

    Inputs must include the source entity columns generated by this project.
    The output deliberately contains identifiers and decision time for auditing,
    but does not contain labels, injected-pattern metadata, raw narrative text,
    or duplicate-reference metadata.
    """
    config = config or FeatureConfig()
    required_claim_columns = {
        "claim_id", "policy_id", "customer_id", "agent_id", "loss_type", "incident_date", "submitted_date", "claim_amount", "narrative"
    }
    missing = required_claim_columns.difference(claims.columns)
    if missing:
        raise ValueError(f"Claims missing required columns: {sorted(missing)}")

    ordered_claims = claims.loc[:, list(required_claim_columns)].copy()
    ordered_claims["submitted_date"] = pd.to_datetime(ordered_claims["submitted_date"])
    ordered_claims["incident_date"] = pd.to_datetime(ordered_claims["incident_date"])
    ordered_claims = ordered_claims.sort_values(["submitted_date", "claim_id"], kind="stable")
    policy_map = policies.set_index("policy_id")
    document_groups = {claim_id: group.copy() for claim_id, group in documents.groupby("claim_id", sort=False)}

    agent_amounts: dict[str, list[float]] = defaultdict(list)
    customer_amounts: dict[str, list[float]] = defaultdict(list)
    customer_claim_counts: dict[str, int] = defaultdict(int)
    customer_type_counts: dict[tuple[str, str], int] = defaultdict(int)
    agent_dates: dict[str, deque[pd.Timestamp]] = defaultdict(deque)
    # Embeddings are local and comparisons use the same strict earlier-date
    # boundary as the rest of this feature builder.  The deployed 22-column
    # model obtains live semantic evidence from the persisted embedding index,
    # so a large artifact rebuild can intentionally omit offline all-pairs
    # columns without changing its approved feature schema.
    similarity_by_claim_id = None
    if include_similarity:
        similarity_features = (similarity_analyzer or NarrativeSimilarityAnalyzer(config.narrative_similarity)).build_features(ordered_claims)
        similarity_by_claim_id = similarity_features.set_index("claim_id")
    historical_narratives: set[str] = set()
    feature_rows: list[dict[str, Any]] = []

    for submitted_date, day_claims in ordered_claims.groupby("submitted_date", sort=True):
        # Strict temporal boundary: no state update occurs until every claim at T is scored.
        for _, claim in day_claims.iterrows():
            agent_id = str(claim["agent_id"])
            customer_id = str(claim["customer_id"])
            loss_type = str(claim["loss_type"])
            amount = float(claim["claim_amount"])
            agent_mean, agent_std = _mean_and_std(agent_amounts[agent_id])
            customer_mean, _ = _mean_and_std(customer_amounts[customer_id])
            recent_dates = agent_dates[agent_id]
            cutoff = pd.Timestamp(submitted_date) - pd.DateOffset(days=config.recent_frequency_window_days)
            while recent_dates and recent_dates[0] < cutoff:
                recent_dates.popleft()
            policy = policy_map.loc[claim["policy_id"]] if claim["policy_id"] in policy_map.index else None
            claim_documents = document_groups.get(claim["claim_id"], pd.DataFrame(columns=documents.columns))
            row = _base_feature_row(claim, policy, claim_documents)
            if similarity_by_claim_id is not None:
                row.update(similarity_by_claim_id.loc[claim["claim_id"]].to_dict())
            row.update(
                {
                    "claim_amount_vs_agent_historical_average": amount / agent_mean if agent_mean else 0.0,
                    "claim_amount_vs_customer_historical_average": amount / customer_mean if customer_mean else 0.0,
                    "claim_frequency": customer_claim_counts[customer_id],
                    "claim_type_frequency": customer_type_counts[(customer_id, loss_type)],
                    "duplicate_similarity": float(str(claim["narrative"]) in historical_narratives),
                    "repeated_customer_claim_indicator": int(customer_claim_counts[customer_id] >= config.repeated_customer_threshold),
                    "agent_historical_claim_count": len(agent_amounts[agent_id]),
                    "agent_historical_average_claim_amount": agent_mean,
                    "agent_historical_claim_amount_std": agent_std,
                    "agent_recent_claim_frequency": len(recent_dates),
                    "agent_behavioral_deviation_score": (amount - agent_mean) / agent_std if agent_std else 0.0,
                }
            )
            feature_rows.append(row)

        for _, claim in day_claims.iterrows():
            agent_id = str(claim["agent_id"])
            customer_id = str(claim["customer_id"])
            loss_type = str(claim["loss_type"])
            agent_amounts[agent_id].append(float(claim["claim_amount"]))
            customer_amounts[customer_id].append(float(claim["claim_amount"]))
            customer_claim_counts[customer_id] += 1
            customer_type_counts[(customer_id, loss_type)] += 1
            agent_dates[agent_id].append(pd.Timestamp(submitted_date))
            historical_narratives.add(str(claim["narrative"]))

    return pd.DataFrame(feature_rows).sort_values("claim_id", kind="stable").reset_index(drop=True)


def _dataframe_from_statement(engine, statement) -> pd.DataFrame:  # type: ignore[no-untyped-def]
    """Load an explicitly selected source statement into a DataFrame."""
    session_factory = get_session_factory(engine)
    with session_factory() as session:
        return pd.read_sql(statement, session.connection())


def build_features_from_database(
    database_path: Path = DEFAULT_DATABASE_PATH,
    config: FeatureConfig | None = None,
    include_similarity: bool = True,
) -> pd.DataFrame:
    """Load source records from SQLite and build the point-in-time feature table."""
    engine = create_engine(database_path)
    claims = _dataframe_from_statement(
        engine,
        select(
            Claim.claim_id,
            Claim.policy_id,
            Claim.customer_id,
            Claim.agent_id,
            Claim.loss_type,
            Claim.incident_date,
            Claim.submitted_date,
            Claim.claim_amount,
            Claim.narrative,
        ),
    )
    policies = _dataframe_from_statement(
        engine,
        select(Policy.policy_id, Policy.policy_status, Policy.effective_date, Policy.expiration_date),
    )
    documents = _dataframe_from_statement(
        engine,
        select(Document.claim_id, Document.document_date, Document.uploaded_date),
    )
    return build_claim_features(claims, policies, documents, config, include_similarity=include_similarity)


def write_features(features: pd.DataFrame, output_path: Path) -> Path:
    """Write features as Parquet, creating the local processed-data directory."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    features.to_parquet(output_path, index=False)
    return output_path


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build point-in-time claim features from SQLite.")
    parser.add_argument("--database", type=Path, default=DEFAULT_DATABASE_PATH, help="Input SQLite database path.")
    parser.add_argument("--output", type=Path, default=FeatureConfig().output_path, help="Output Parquet path.")
    parser.add_argument("--skip-semantic-features", action="store_true", help="Omit offline all-pairs semantic columns; live retrieval remains available through the embedding index.")
    return parser.parse_args()


def main() -> None:
    """Run the feature-engineering command."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    args = _parse_args()
    features = build_features_from_database(args.database, include_similarity=not args.skip_semantic_features)
    output_path = write_features(features, args.output)
    LOGGER.info("Generated %s point-in-time feature rows at %s", len(features), output_path)


if __name__ == "__main__":
    main()
